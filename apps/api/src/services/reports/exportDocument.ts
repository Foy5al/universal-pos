import type { ReportExportKind, SalesSummary, StoreActivity } from '@pos/contracts';

import type { ExportRow, ReportDocument } from '../../exports/tabular';

export interface ExportContext {
  organizationId: string;
  email: string;
  from: string;
  to: string;
  locationLabel: string;
}

const TITLES: Record<ReportExportKind, string> = {
  'sales-summary': 'Sales summary',
  'store-activity': 'Store activity',
};

function meta(kind: ReportExportKind, context: ExportContext): string[] {
  return [
    `Universal POS - ${TITLES[kind]}`,
    `Organization: ${context.organizationId}`,
    `Locations: ${context.locationLabel}`,
    `Range (UTC): ${context.from} to ${context.to}`,
    `Generated by: ${context.email}`,
    'Amounts are integer minor units; net sales = gross sales - refunds.',
  ];
}

function filenameStem(kind: ReportExportKind, context: ExportContext): string {
  return `${kind}-${context.from.slice(0, 10)}-${context.to.slice(0, 10)}`;
}

export function salesSummaryDocument(
  summary: SalesSummary,
  context: ExportContext,
): ReportDocument {
  const columns = [
    { key: 'date', header: 'Date (UTC)', width: 14 },
    { key: 'saleCount', header: 'Sales', width: 10 },
    { key: 'refundCount', header: 'Refunds', width: 10 },
    { key: 'grossSalesMinor', header: 'Gross sales (minor)', width: 20 },
    { key: 'refundsMinor', header: 'Refund value (minor)', width: 20 },
    { key: 'netSalesMinor', header: 'Net sales (minor)', width: 18 },
    { key: 'unitsSold', header: 'Units', width: 12 },
  ];
  const totals: ExportRow = {
    date: 'Total',
    saleCount: summary.saleCount,
    refundCount: summary.refundCount,
    grossSalesMinor: summary.grossSalesMinor,
    refundsMinor: summary.refundsMinor,
    netSalesMinor: summary.netSalesMinor,
    unitsSold: summary.unitsSold,
  };
  return {
    kind: 'sales-summary',
    title: TITLES['sales-summary'],
    filenameStem: filenameStem('sales-summary', context),
    meta: meta('sales-summary', context),
    columns,
    rows: summary.days.map((day) => ({ ...day })),
    totals,
  };
}

export function storeActivityDocument(
  activity: StoreActivity,
  context: ExportContext,
): ReportDocument {
  return {
    kind: 'store-activity',
    title: TITLES['store-activity'],
    filenameStem: filenameStem('store-activity', context),
    meta: meta('store-activity', context),
    columns: [
      { key: 'metric', header: 'Metric', width: 18 },
      { key: 'count', header: 'Count', width: 10 },
      { key: 'units', header: 'Units', width: 14 },
      { key: 'valueMinor', header: 'Value (minor)', width: 18 },
    ],
    rows: [
      {
        metric: 'Sales',
        count: activity.sales.saleCount,
        units: activity.sales.unitsSold,
        valueMinor: activity.sales.grossSalesMinor,
      },
      {
        metric: 'Refunds',
        count: activity.sales.refundCount,
        units: null,
        valueMinor: activity.sales.refundsMinor,
      },
      {
        metric: 'Net sales',
        count: null,
        units: null,
        valueMinor: activity.sales.netSalesMinor,
      },
      {
        metric: 'Stock losses',
        count: activity.losses.count,
        units: activity.losses.units,
        valueMinor: activity.losses.costValueMinor,
      },
      {
        metric: 'Receiving',
        count: activity.receiving.count,
        units: activity.receiving.units,
        valueMinor: activity.receiving.costValueMinor,
      },
    ],
  };
}
